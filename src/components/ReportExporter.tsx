export default function ReportExporter({ 
  profile, 
  periods, 
  analysis, 
  budgetPerformance = [],
  variant = 'card',
  onClose
}: ReportExporterProps) {
  const { t } = useTranslation();
  const [downloadSuccess, setDownloadSuccess] = useState<string | null>(null);

  // Independently selectable report language
  const [reportLang, setReportLang] = useState<SupportedLanguageCode>(() => getReportGenerationLanguage());

  const curSymbol = profile.currency?.match(/\(([^)]+)\)/)?.[1] || profile.currency?.split(' ')[0] || '$';
  const sortedPeriods = [...periods].sort((a, b) => b.period.localeCompare(a.period, undefined, { numeric: true }));
  const currPeriod = sortedPeriods[0];
  const priorPeriod = sortedPeriods.length > 1 ? sortedPeriods[1] : null;

  const showToast = (msg: string) => {
    setDownloadSuccess(msg);
    setTimeout(() => setDownloadSuccess(null), 3000);
  };

  const dict = REPORT_DICTIONARY[reportLang] || REPORT_DICTIONARY.en;

  // 1. EXCEL WORKBOOK MULTI-SHEET EXPORT (.xlsx)
  const exportToExcelWorkbook = () => {
    if (!currPeriod) return;

    try {
      const wb = XLSX.utils.book_new();

      // Sheet 1: Executive Briefing & KPIs
      const ratiosCurr = calculateFinancialRatios(currPeriod, priorPeriod);
      const dupont = calculateDuPont(currPeriod);
      const isCurr = currPeriod.incomeStatement;

      const summaryRows = [
        [dict.reportHeader],
        [dict.tagline],
        [''],
        [`${dict.metaCompany}:`, profile.companyName],
        [`${dict.metaIndustry}:`, profile.industry],
        [`${dict.metaJurisdiction}:`, profile.location],
        [`${dict.metaCurrency}:`, profile.currency],
        [`${dict.metaFramework}:`, profile.reportingBasis || 'IFRS'],
        [`${dict.metaPeriod}:`, currPeriod.period],
        [`${dict.metaDate}:`, new Date().toLocaleDateString()],
        [''],
        ['CORE EXECUTIVE KPIS', currPeriod.period, priorPeriod ? priorPeriod.period : 'Prior', 'Benchmark Target'],
        [dict.revenue, isCurr.revenue, priorPeriod ? priorPeriod.incomeStatement.revenue : 'N/A', 'Growth Target'],
        ['Gross Margin (%)', `${safeDiv(isCurr.grossProfit, isCurr.revenue, 100).toFixed(1)}%`, priorPeriod ? `${safeDiv(priorPeriod.incomeStatement.grossProfit, priorPeriod.incomeStatement.revenue, 100).toFixed(1)}%` : 'N/A', '25.0%'],
        ['Operating Margin (%)', `${safeDiv(isCurr.operatingIncome, isCurr.revenue, 100).toFixed(1)}%`, priorPeriod ? `${safeDiv(priorPeriod.incomeStatement.operatingIncome, priorPeriod.incomeStatement.revenue, 100).toFixed(1)}%` : 'N/A', '12.0%'],
        ['Net Margin (%)', `${safeDiv(isCurr.netIncome, isCurr.revenue, 100).toFixed(1)}%`, priorPeriod ? `${safeDiv(priorPeriod.incomeStatement.netIncome, priorPeriod.incomeStatement.revenue, 100).toFixed(1)}%` : 'N/A', '8.0%'],
        ['Current Ratio (x)', ratiosCurr.currentRatio.toFixed(2), priorPeriod ? calculateFinancialRatios(priorPeriod).currentRatio.toFixed(2) : 'N/A', '1.50x'],
        ['Return on Equity (%)', `${dupont.roe.toFixed(1)}%`, 'N/A', '15.0%'],
        ['Altman Z-Score', ratiosCurr.altmanZScore.toFixed(2), 'N/A', '2.90 Safe Zone'],
        ['Risk Rating (1 to 10)', `${ratiosCurr.riskScore.toFixed(1)} / 10`, 'N/A', '< 4.0 Low Risk'],
      ];
      const wsSummary = XLSX.utils.aoa_to_sheet(summaryRows);
      XLSX.utils.book_append_sheet(wb, wsSummary, 'Executive Summary');

      // Sheet 2: Statement of Profit or Loss
      const pnlRows: any[][] = [
        [dict.secPnl, `${dict.metaCurrency}: ${profile.currency}`],
        [dict.accountLine, ...sortedPeriods.map(p => p.period)],
        [dict.revenue, ...sortedPeriods.map(p => p.incomeStatement.revenue)],
        [dict.cogs, ...sortedPeriods.map(p => -p.incomeStatement.cogs)],
        [dict.grossProfit, ...sortedPeriods.map(p => p.incomeStatement.grossProfit)],
        [dict.opex, ...sortedPeriods.map(p => -p.incomeStatement.operatingExpenses.total)],
        [dict.ebit, ...sortedPeriods.map(p => p.incomeStatement.operatingIncome)],
        [dict.tax, ...sortedPeriods.map(p => -p.incomeStatement.taxExpense)],
        [dict.netIncome, ...sortedPeriods.map(p => p.incomeStatement.netIncome)]
      ];
      const wsPnl = XLSX.utils.aoa_to_sheet(pnlRows);
      XLSX.utils.book_append_sheet(wb, wsPnl, 'Income Statement');

      // Sheet 3: Statement of Financial Position
      const bsRows: any[][] = [
        ['Statement of Financial Position', `${dict.metaCurrency}: ${profile.currency}`],
        [dict.accountLine, ...sortedPeriods.map(p => p.period)],
        ['Total Assets', ...sortedPeriods.map(p => p.balanceSheet.assets.totalAssets)],
        ['Current Assets', ...sortedPeriods.map(p => p.balanceSheet.assets.totalCurrentAssets)],
        ['Total Liabilities', ...sortedPeriods.map(p => p.balanceSheet.liabilities.totalLiabilities)],
        ['Total Equity', ...sortedPeriods.map(p => p.balanceSheet.equity.totalEquity)]
      ];
      const wsBs = XLSX.utils.aoa_to_sheet(bsRows);
      XLSX.utils.book_append_sheet(wb, wsBs, 'Balance Sheet');

      // Sheet 4: Management Accounts & Budget Variance
      if (budgetPerformance.length > 0) {
        const bRows: any[][] = [
          [dict.secBudget],
          [dict.budgetCategory, dict.budgetTarget, dict.actualResult, dict.variance, 'Variance %', dict.impact],
          ...budgetPerformance.map(b => [
            b.category,
            b.budgeted,
            b.actual,
            b.variance,
            `${b.variancePercentage.toFixed(1)}%`,
            (/revenue/i.test(b.category) ? b.variance >= 0 : b.variance <= 0) ? dict.favorable : dict.unfavorable
          ])
        ];
        const wsBudget = XLSX.utils.aoa_to_sheet(bRows);
        XLSX.utils.book_append_sheet(wb, wsBudget, 'Budget Variance');
      }

      // Write and download
      const fileName = `${profile.companyName || 'FinScope'}_Report_${currPeriod.period}_${reportLang.toUpperCase()}.xlsx`;
      XLSX.writeFile(wb, fileName);
      showToast(`Excel workbook exported successfully (${reportLang.toUpperCase()}).`);
    } catch (err: any) {
      console.error('Failed to export Excel workbook:', err);
    }
  };

  // 2. WORD DOCUMENT EXPORT (.doc format)
  const exportToWordDocument = () => {
    if (!currPeriod) return;

    const isRTL = reportLang === 'ar';
    let docHtml = `<html xmlns:o='urn:schemas-microsoft-com:office:office' xmlns:w='urn:schemas-microsoft-com:office:word' xmlns='http://www.w3.org/TR/REC-html40'>`;
    docHtml += `<head><title>${dict.reportHeader}</title>`;
    docHtml += `<style>
      body { font-family: 'Calibri', 'Arial', sans-serif; line-height: 1.5; color: #0B192C; margin: 40px; ${isRTL ? 'direction: rtl; text-align: right;' : 'text-align: left;'} }
      h1 { color: #0B1530; font-size: 22pt; border-bottom: 3px solid #D6AE55; padding-bottom: 8px; margin-bottom: 4px; }
      .tagline { color: #64748b; font-size: 11pt; font-style: italic; margin-bottom: 20px; }
      h2 { color: #0B1530; font-size: 13pt; margin-top: 18pt; border-bottom: 1px solid #E8E2D8; padding-bottom: 4px; }
      .meta-box { background: #FAF7F2; border: 1px solid #E8E2D8; padding: 12px; margin-bottom: 20px; font-size: 10pt; }
      table { width: 100%; border-collapse: collapse; margin: 12px 0; font-size: 10pt; }
      th { background-color: #0B1530; color: #ffffff; border: 1px solid #162A45; padding: 6px 10px; ${isRTL ? 'text-align: right;' : 'text-align: left;'} }
      td { border: 1px solid #E8E2D8; padding: 6px 10px; }
      .num { text-align: right; font-family: 'Consolas', monospace; }
      .kpi-score { font-size: 13pt; font-weight: bold; color: #0B1530; }
      .footer { font-size: 9pt; color: #94a3b8; text-align: center; margin-top: 40px; border-top: 1px solid #E8E2D8; padding-top: 10px; }
    </style></head><body>`;

    docHtml += `<h1>${dict.reportHeader}</h1>`;
    docHtml += `<div class="tagline">${dict.tagline}</div>`;

    docHtml += `<div class="meta-box">`;
    docHtml += `<b>${dict.metaCompany}:</b> ${profile.companyName} &nbsp;|&nbsp; <b>${dict.metaIndustry}:</b> ${profile.industry}<br/>`;
    docHtml += `<b>${dict.metaJurisdiction}:</b> ${profile.location} &nbsp;|&nbsp; <b>${dict.metaCurrency}:</b> ${profile.currency}<br/>`;
    docHtml += `<b>${dict.metaFramework}:</b> ${profile.reportingBasis || 'IFRS'} &nbsp;|&nbsp; <b>${dict.metaDate}:</b> ${new Date().toLocaleDateString()}<br/>`;
    docHtml += `</div>`;

    // 1. Executive Summary
    docHtml += `<h2>${dict.secSummary}</h2>`;
    if (analysis?.executiveSummary) {
      docHtml += `<p>${analysis.executiveSummary.replace(/\n/g, '<br/>')}</p>`;
    } else {
      docHtml += `<p>Empirical financial evaluation for ${currPeriod.period} completed with deterministic ratio calibrations.</p>`;
    }

    const ratiosCurr = calculateFinancialRatios(currPeriod, priorPeriod);
    const dupont = calculateDuPont(currPeriod);

    docHtml += `<p class="kpi-score">${dict.kpiHealthScore}: <b>${analysis?.financialHealthScore || Math.round(10 - ratiosCurr.riskScore)} / 10</b> &nbsp;|&nbsp; ${dict.kpiAltman}: <b>${ratiosCurr.altmanZScore.toFixed(2)}</b></p>`;
    docHtml += `<p><b>${dict.kpiDuPont}:</b> ${dupont.formulaDisplay}</p>`;

    // 2. Comparative Income Statement
    docHtml += `<h2>${dict.secPnl}</h2>`;
    docHtml += `<table><thead><tr><th>${dict.accountLine}</th>`;
    sortedPeriods.forEach(p => {
      docHtml += `<th class="num">${p.period}</th>`;
    });
    docHtml += `</tr></thead><tbody>`;
    docHtml += `<tr><td><b>${dict.revenue}</b></td>${sortedPeriods.map(p => `<td class="num"><b>${formatLocaleNumber(p.incomeStatement.revenue, { decimals: 0 })}</b></td>`).join('')}</tr>`;
    docHtml += `<tr><td>${dict.cogs}</td>${sortedPeriods.map(p => `<td class="num">(${formatLocaleNumber(p.incomeStatement.cogs, { decimals: 0 })})</td>`).join('')}</tr>`;
    docHtml += `<tr><td><b>${dict.grossProfit}</b></td>${sortedPeriods.map(p => `<td class="num"><b>${formatLocaleNumber(p.incomeStatement.grossProfit, { decimals: 0 })}</b></td>`).join('')}</tr>`;
    docHtml += `<tr><td>${dict.opex}</td>${sortedPeriods.map(p => `<td class="num">(${formatLocaleNumber(p.incomeStatement.operatingExpenses.total, { decimals: 0 })})</td>`).join('')}</tr>`;
    docHtml += `<tr><td><b>${dict.ebit}</b></td>${sortedPeriods.map(p => `<td class="num"><b>${formatLocaleNumber(p.incomeStatement.operatingIncome, { decimals: 0 })}</b></td>`).join('')}</tr>`;
    docHtml += `<tr><td>${dict.tax}</td>${sortedPeriods.map(p => `<td class="num">(${formatLocaleNumber(p.incomeStatement.taxExpense, { decimals: 0 })})</td>`).join('')}</tr>`;
    docHtml += `<tr><td><b>${dict.netIncome}</b></td>${sortedPeriods.map(p => `<td class="num"><b>${formatLocaleNumber(p.incomeStatement.netIncome, { decimals: 0 })}</b></td>`).join('')}</tr>`;
    docHtml += `</tbody></table>`;

    // 3. Budget Variances
    if (budgetPerformance.length > 0) {
      docHtml += `<h2>${dict.secBudget}</h2>`;
      docHtml += `<table><thead><tr><th>${dict.budgetCategory}</th><th class="num">${dict.budgetTarget}</th><th class="num">${dict.actualResult}</th><th class="num">${dict.variance}</th><th class="num">Var %</th><th>${dict.impact}</th></tr></thead><tbody>`;
      budgetPerformance.forEach(b => {
        const isFav = /revenue/i.test(b.category) ? b.variance >= 0 : b.variance <= 0;
        docHtml += `<tr><td>${b.category}</td><td class="num">${formatLocaleNumber(b.budgeted, { decimals: 0 })}</td><td class="num"><b>${formatLocaleNumber(b.actual, { decimals: 0 })}</b></td><td class="num">${b.variance >= 0 ? '+' : ''}${formatLocaleNumber(b.variance, { decimals: 0 })}</td><td class="num">${b.variancePercentage.toFixed(1)}%</td><td><b>${isFav ? dict.favorable : dict.unfavorable}</b></td></tr>`;
      });
      docHtml += `</tbody></table>`;
    }

    docHtml += `<div class="footer">${dict.confidentialFooter}</div>`;
    docHtml += `</body></html>`;

    const blob = new Blob([docHtml], { type: 'application/msword' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.setAttribute('download', `${profile.companyName || 'FinScope'}_CFO_Report_${currPeriod.period}_${reportLang.toUpperCase()}.doc`);
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    showToast(`Word document exported successfully (${reportLang.toUpperCase()}).`);
  };

  // 3. PRINT / PDF EXPORT
  const triggerPDFPrint = () => {
    window.print();
    showToast('Print dialog triggered.');
  };

  const handleReportLanguageChange = (newLang: SupportedLanguageCode) => {
    setReportLang(newLang);
    setReportGenerationLanguage(newLang);
  };

  if (variant === 'compact') {
    return (
      <div className="flex items-center gap-2">
        <LanguageSelector
          variant="compact"
          customSelectedLanguage={reportLang}
          onLanguageChange={handleReportLanguageChange}
        />
        <button
          type="button"
          onClick={exportToExcelWorkbook}
          className="px-3 py-1.5 bg-white hover:bg-[#FAF7F2] border border-[#E8E2D8] text-xs font-semibold text-[#0B192C] rounded-lg shadow-xs flex items-center gap-1.5 cursor-pointer transition-colors"
          title="Export Excel (.xlsx)"
        >
          <FileSpreadsheet className="w-3.5 h-3.5 text-emerald-700" />
          <span>Excel</span>
        </button>

        <button
          type="button"
          onClick={exportToWordDocument}
          className="px-3 py-1.5 bg-white hover:bg-[#FAF7F2] border border-[#E8E2D8] text-xs font-semibold text-[#0B192C] rounded-lg shadow-xs flex items-center gap-1.5 cursor-pointer transition-colors"
          title="Export Word (.doc)"
        >
          <FileText className="w-3.5 h-3.5 text-blue-700" />
          <span>Word</span>
        </button>

        <button
          type="button"
          onClick={triggerPDFPrint}
          className="px-3 py-1.5 bg-[#0B1530] hover:bg-[#162A45] text-white text-xs font-semibold rounded-lg shadow-xs flex items-center gap-1.5 cursor-pointer transition-colors"
          title="Print / Save PDF"
        >
          <Printer className="w-3.5 h-3.5 text-[#D6AE55]" />
          <span>Print / PDF</span>
        </button>
      </div>
    );
  }

  return (
    <div className="bg-white border border-[#E8E2D8] rounded-2xl p-6 sm:p-7 shadow-xs text-left space-y-4" id="report-exporter-card">
      <div className="flex flex-col lg:flex-row items-start lg:items-center justify-between gap-6">
        <div>
          <div className="flex items-center gap-2 mb-1 flex-wrap">
            <span className="text-[10px] font-mono uppercase font-bold text-[#D6AE55] tracking-wider">
              MULTI-FORMAT EXPORT ENGINE
            </span>
            <span className="text-slate-300">·</span>
            <span className="text-xs text-slate-500 font-mono">
              {profile.companyName} ({currPeriod?.period || 'Current'})
            </span>
          </div>
          <h3 className="font-serif-display text-xl font-bold text-[#0B192C]">
            Export Board-Ready Financial Intelligence Reports
          </h3>
          <p className="text-xs text-slate-600 mt-1 max-w-2xl leading-relaxed">
            Generate executive deliverables formatted for CFOs, board directors, lenders, auditors, and investors. Includes complete financial statements, ratio scorecards, DuPont ROE, and variance investigations.
          </p>
        </div>

        {/* Independent Report Language Switcher */}
        <div className="flex flex-col sm:flex-row items-start sm:items-center gap-3 bg-[#FAF7F2] p-3 rounded-xl border border-[#E8E2D8] shrink-0">
          <div className="flex items-center gap-1.5 text-xs">
            <Globe className="w-3.5 h-3.5 text-[#D6AE55]" />
            <span className="font-bold text-[#0B192C]">Report Language:</span>
          </div>
          <LanguageSelector
            variant="compact"
            customSelectedLanguage={reportLang}
            onLanguageChange={handleReportLanguageChange}
          />
        </div>
      </div>

      {/* Statutory Preservation Notice */}
      <div className="text-[11px] text-slate-500 bg-amber-50/50 p-2.5 rounded-xl border border-amber-200/60 flex items-center gap-2">
        <Info className="w-4 h-4 text-amber-700 shrink-0" />
        <span>
          <strong>Faithful Data Guarantee:</strong> Financial figures, company names, account codes, and dates remain 100% faithful to the original records. Report headings and structural narratives will be translated into <strong>{SUPPORTED_LANGUAGES.find(l => l.code === reportLang)?.name}</strong>.
        </span>
      </div>

      {/* Action Export Buttons */}
      <div className="flex flex-wrap items-center justify-end gap-3 pt-2 border-t border-[#E8E2D8]">
        {/* Excel XLSX */}
        <button
          type="button"
          onClick={exportToExcelWorkbook}
          className="px-4 py-2 bg-white hover:bg-[#FAF7F2] border border-[#E8E2D8] text-slate-800 text-xs font-semibold rounded-xl shadow-xs flex items-center gap-2 cursor-pointer transition-colors hover:border-emerald-600/40"
          title="Download multi-tab Excel workbook"
        >
          <FileSpreadsheet className="w-4 h-4 text-emerald-700" />
          <span>Excel Workbook (.xlsx)</span>
        </button>

        {/* Word DOC */}
        <button
          type="button"
          onClick={exportToWordDocument}
          className="px-4 py-2 bg-white hover:bg-[#FAF7F2] border border-[#E8E2D8] text-slate-800 text-xs font-semibold rounded-xl shadow-xs flex items-center gap-2 cursor-pointer transition-colors hover:border-blue-600/40"
          title="Download editable Word memorandum"
        >
          <FileText className="w-4 h-4 text-blue-700" />
          <span>Word Report (.doc)</span>
        </button>

        {/* Print PDF */}
        <button
          type="button"
          onClick={triggerPDFPrint}
          className="px-5 py-2 bg-[#0B1530] hover:bg-[#162A45] text-white text-xs font-bold rounded-xl shadow-xs flex items-center gap-2 cursor-pointer transition-colors"
          title="Print or Save as PDF"
        >
          <Printer className="w-4 h-4 text-[#D6AE55]" />
          <span>Print / PDF Presentation</span>
        </button>
      </div>

      {downloadSuccess && (
        <div className="p-3 bg-emerald-50 border border-emerald-200 rounded-xl text-xs text-emerald-800 flex items-center gap-2 font-medium animate-fade-in">
          <CheckCircle2 className="w-4 h-4 text-emerald-600" />
          <span>{downloadSuccess}</span>
        </div>
      )}
    </div>
  );
}
